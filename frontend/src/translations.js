export function translateCommentary(commentary, lang) {
  if (!commentary || lang !== 'hi') return commentary;

  // 1. Neck and neck
  if (commentary.includes('is neck and neck. The bell saves both corners.')) {
    const metric = commentary.split(' is neck and neck')[0];
    const metricTrans = {
      'Promise Delivery': 'वादों की पूर्ति',
      'Citizen Progress': 'नागरिक प्रगति',
      'Area Condition': 'क्षेत्रीय स्थिति',
      'Verified Evidence': 'सत्यापित साक्ष्य',
      'Neta Meter Score': 'नेता मीटर स्कोर',
    }[metric] || metric;
    return `${metricTrans} में कांटे की टक्कर है। घंटी ने दोनों को बराबरी पर बचाया।`;
  }

  // 2. Stronger citizen progress reports led by category
  const matchCat = commentary.match(/^(.*?) lands the cleaner round with stronger citizen progress reports, led by (.*?)\.?$/);
  if (matchCat) {
    const leader = matchCat[1];
    const category = matchCat[2];
    const leaderTrans = politicianTranslations[leader]?.name || leader;
    const catTrans = categoryTranslations[category?.toLowerCase()]?.hi || category;
    return `${leaderTrans} ने ${catTrans} के दम पर मजबूत नागरिक प्रगति रिपोर्ट के साथ राउंड अपने नाम किया।`;
  }

  // 3. Evidence verification edge
  const matchEvidence = commentary.match(/^(.*?) takes the evidence round with a ([\d.]+)-point verification edge\.?$/);
  if (matchEvidence) {
    const leader = matchEvidence[1];
    const gap = matchEvidence[2];
    const leaderTrans = politicianTranslations[leader]?.name || leader;
    return `${leaderTrans} ने ${gap}-अंकों की सत्यापन बढ़त के साथ साक्ष्य राउंड जीता।`;
  }

  // 4. Wins round by X points
  const matchPoints = commentary.match(/^(.*?) wins this round by ([\d.]+) points\.?$/);
  if (matchPoints) {
    const leader = matchPoints[1];
    const gap = matchPoints[2];
    const leaderTrans = politicianTranslations[leader]?.name || leader;
    return `${leaderTrans} ने यह राउंड ${gap} अंकों से जीता।`;
  }

  return commentary;
}
